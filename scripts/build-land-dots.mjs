/**
 * Samples the world's land masses on the same projection the UN emblem uses
 * (azimuthal equidistant, centred on the North Pole, cut at 60°S, Greenwich
 * meridian pointing down) and writes them as a compact Int16 dot grid.
 *
 *   node scripts/build-land-dots.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

// world-atlas polygons are already cut at the antimeridian, so a planar
// even-odd test in lon/lat space is exact here (and avoids d3's spherical
// winding ambiguity on continent-sized rings).
const rings = land.features.flatMap((f) =>
  f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.coordinates.flat());
function onLand(lon, lat) {
  let inside = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i], [xj, yj] = ring[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const SOUTH_LIMIT = -60;           // the emblem stops at 60°S
const ARC = 90 - SOUTH_LIMIT;      // degrees of latitude covered by the disc
const STEP = 0.0165;               // grid pitch in unit-disc coordinates

const out = [];
for (let y = -1; y <= 1; y += STEP) {
  for (let x = -1; x <= 1; x += STEP) {
    const r = Math.hypot(x, y);
    if (r > 1) continue;
    const lat = 90 - r * ARC;
    const lon = (Math.atan2(x, y) * 180) / Math.PI;
    if (onLand(lon, lat)) out.push(Math.round(x * 32000), Math.round(y * 32000));
  }
}

const b64 = Buffer.from(new Int16Array(out).buffer).toString('base64');
writeFileSync(
  new URL('../src/data/landDots.ts', import.meta.url),
  `/* Generated by scripts/build-land-dots.mjs. Do not edit by hand. */\n` +
  `/* ${out.length / 2} land dots, Int16 pairs (x, y) scaled by 32000, unit disc, y down. */\n` +
  `export const LAND_DOTS_B64 =\n  '${b64}';\n`,
);
console.log(`${out.length / 2} dots, ${b64.length} base64 chars`);
